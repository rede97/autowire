// Build the standalone dtsim.js: refresh the embedded DSL source, then let
// Bun bundle the CLI and the built-in backends into one file.
import { spawnSync } from "node:child_process";
import { join } from "node:path";

const root = join(import.meta.dir, "..");
const dslPath = join(root, "dtsim", "dsl", "index.ts");
const source = await Bun.file(dslPath).text();
const embedded = `// GENERATED by dtsim/build.ts from dsl/index.ts. Do not edit by hand.
// dt/dsl-env.test.ts fails when the two drift apart.
export const DSL_SOURCE = ${JSON.stringify(source)};
`;
await Bun.write(join(root, "dtsim", "dsl", "embedded.generated.ts"), embedded);

const result = spawnSync(
	"bun",
	["build", "dtsim/index.ts", "--target", "bun", "--outfile", "dtsim.js"],
	{ cwd: root, stdio: "inherit" },
);
if (result.status !== 0) {
	throw new Error(`dtsim: bundle failed with exit code ${result.status}`);
}
console.log("wrote dtsim.js");
