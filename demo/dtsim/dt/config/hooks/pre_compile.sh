#!/usr/bin/env bash
# preCompile hook (demo/dtsim): generate source the build needs, once per
# compile directory. Here: a stamp header with the case and git revision.
# Typical uses: code generation, IP patching, prebuilding a C model, license
# checks. A non-zero exit stops this compile (Hook fail: "stop", the default).
# Args: --phase --case --dir --tool --log; cwd is the compile dir; env is the
# isolated compile env plus DTSIM_HOOK.
set -euo pipefail
while [[ $# -gt 0 ]]; do
	case "$1" in
	--case) CASE="$2"; shift 2 ;;
	--dir) DIR="$2"; shift 2 ;;
	*) shift 2 ;;
	esac
done
rev=$(cat "$DIR/git_rev" 2>/dev/null | head -1 || true)
cat >"$DIR/gen_stamp.svh" <<EOF
// Generated by dt/config/hooks/pre_compile.sh. Do not edit.
\`define DTSIM_CASE "${CASE}"
\`define DTSIM_REV "${rev:-unknown}"
EOF
echo "pre_compile: wrote $DIR/gen_stamp.svh"
