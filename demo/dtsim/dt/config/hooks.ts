// demo/dtsim hooks: one TypeScript function per stage. Every hook receives the
// same HookContext (case, dir, log, merged options, isolated env, expand,
// resolvePath, sh); sim stages add `seed`, onResult adds `status`. A throw
// fails that compile / seed (onResult only logs it).
import { appendFile, readFile, rm, writeFile } from "node:fs/promises";
import { dirname, join } from "node:path";
import type { HookContext } from "../../../../src/dtsim/dsl/index.ts";

/** preCompile: copy the SPICE deck into the compile dir with placeholders
 *  expanded, for cosim cases only (what `patches` used to do). */
export async function spiceDeck(ctx: HookContext): Promise<void> {
	if (!ctx.caseId.includes(".cosim")) return;
	// biome-ignore lint/suspicious/noTemplateCurlyInString: dtsim placeholder, expanded by ctx.resolvePath
	const deck = await readFile(ctx.resolvePath("${verify}/cosim/spice/input.sp"), "utf8");
	await writeFile(join(ctx.dir, "input.sp"), ctx.expand(deck));
}

/** preCompile: generate a header the build includes. `ctx.sh` runs a shell
 *  command in the compile dir with the compile env; output lands in
 *  hook-preCompile.log. */
export async function stampHeader(ctx: HookContext): Promise<void> {
	const built = (await ctx.sh("date -u +%Y-%m-%dT%H:%M:%SZ")).trim();
	await writeFile(
		join(ctx.dir, "gen_stamp.svh"),
		`// Generated by dt/config/hooks.ts. Do not edit.\n\`define DTSIM_CASE "${ctx.caseId}"\n\`define DTSIM_BUILT "${built}"\n`,
	);
}

/** postCompile: a compile-log policy the simulator does not enforce:
 *  fail when the log has more warnings than DTSIM_DEMO_MAX_WARN (default 50). */
export async function warningBudget(ctx: HookContext): Promise<void> {
	const text = await readFile(ctx.log, "utf8").catch(() => "");
	const count = text.split("\n").filter((l) => l.includes("Warning-[")).length;
	const max = Number(ctx.env.DTSIM_DEMO_MAX_WARN ?? 50);
	if (count > max) {
		throw new Error(`${count} compile warnings in ${ctx.log} (limit ${max})`);
	}
}

/** preSim: per-seed stimulus, so a failing seed replays from its directory. */
export async function stimulus(ctx: HookContext): Promise<void> {
	let x = Number(ctx.seed) >>> 0 || 1;
	const words: string[] = [];
	for (let i = 0; i < 4; i++) {
		x = (x * 1103515245 + 12345) >>> 0;
		words.push(x.toString(16).padStart(8, "0"));
	}
	await writeFile(join(ctx.dir, "stim.hex"), `${words.join("\n")}\n`);
}

/** postSim: post-process before grading; a golden compare would throw here. */
export async function metrics(ctx: HookContext): Promise<void> {
	const lines = (await readFile(ctx.log, "utf8").catch(() => "")).split("\n");
	await writeFile(
		join(ctx.dir, "metrics.json"),
		`${JSON.stringify({
			case: ctx.caseId,
			seed: ctx.seed,
			log_lines: lines.length,
			error_lines: lines.filter((l) => l.includes("Error")).length,
		})}\n`,
	);
}

/** onResult: one CSV row per seed next to the case directories
 *  (<out>/<case>/<seed> for run, <out>/regression/<case>/<seed> for regr),
 *  and drop the waveform of passing seeds. */
export async function recordResult(ctx: HookContext): Promise<void> {
	const csv = join(dirname(dirname(ctx.dir)), "results.csv");
	const header = await readFile(csv, "utf8").then(
		() => "",
		() => "case,seed,status,dir\n",
	);
	await appendFile(csv, `${header}${ctx.caseId},${ctx.seed},${ctx.status},${ctx.dir}\n`);
	if (ctx.status === "PASS")
		await rm(join(ctx.dir, `${ctx.caseId}.fsdb`), { force: true });
}
