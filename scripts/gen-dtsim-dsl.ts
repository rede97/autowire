// Refresh src/dtsim/dsl/embedded.generated.ts from the src/dtsim/dsl/ sources.
// autowire.js embeds the DSL text and materializes it into
// <project>/dt/config/.dtsim/dsl/ on every dtsim run.
// test/dtsim/dsl-env.test.ts fails when the two drift apart.

import { join } from "node:path";
import { Glob } from "bun";

const dir = join(import.meta.dir, "..", "src", "dtsim", "dsl");
const target = join(dir, "embedded.generated.ts");
const files: Record<string, string> = {};
for (const rel of [...new Glob("**/*.ts").scanSync(dir)].sort()) {
	const path = rel.replaceAll("\\", "/");
	if (path === "embedded.generated.ts") continue;
	files[path] = await Bun.file(join(dir, rel)).text();
}
const body = `// GENERATED by scripts/gen-dtsim-dsl.ts from src/dtsim/dsl/. Do not edit by hand.
// test/dtsim/dsl-env.test.ts fails when the two drift apart.
export const DSL_FILES: Record<string, string> = ${JSON.stringify(files, null, "\t")};
`;
const current = await Bun.file(target)
	.text()
	.catch(() => "");
if (current !== body) {
	await Bun.write(target, body);
	console.log(`dtsim dsl: wrote ${target}`);
}
