// Refresh src/dtsim/dsl/embedded.generated.ts from src/dtsim/dsl/index.ts.
// autowire.js embeds the DSL text and materializes it into
// <project>/dt/config/.dtsim/dsl/index.ts on every dtsim run.
// test/dtsim/dsl-env.test.ts fails when the two drift apart.

import { join } from "node:path";

const dir = join(import.meta.dir, "..", "src", "dtsim", "dsl");
const source = await Bun.file(join(dir, "index.ts")).text();
const target = join(dir, "embedded.generated.ts");
const body = `// GENERATED by scripts/gen-dtsim-dsl.ts from dsl/index.ts. Do not edit by hand.
// test/dtsim/dsl-env.test.ts fails when the two drift apart.
export const DSL_SOURCE = ${JSON.stringify(source)};
`;
const current = await Bun.file(target)
	.text()
	.catch(() => "");
if (current !== body) {
	await Bun.write(target, body);
	console.log(`dtsim dsl: wrote ${target}`);
}
