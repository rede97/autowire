describe("doc examples: generated SV equals the doc", () => {
	const modules = [
		"cmp_fsm",
		"cfg_load",
		"burst_ctl",
		"scan_ctl",
		"step_ctl",
		"act_demo",
		"msg_fwd",
		"reg_demo",
		"phy_init",
		"dump_check",
		"dump_server",
		"dump_client",
		"reg_mgr",
		"reg_mgr_reg",
		"work_ctl",
		"soft_rst_ctl",
		"err_ctl",
		"phy_mon",
		"cmd",
	];
	// §5.3 imports the §5.2 source; a Caller server is compiled from its caller's DSL.
	const more = () => ({ "dump_check.mjs": docDsl("dump_check").text });
	// "cmd" is the §2.8 block: package cmd_pkg, then module cmd_post.
	const from: Record<string, string> = {
		reg_mgr_reg: "reg_mgr",
		cmd: "cmd_post",
	};
	for (const name of modules)
		test(name, async () => {
			const dsl = docDsl(from[name] ?? name);
			const sv = dsl.whole
				? await compileText(dsl.text, more())
				: await compileBody(dsl.text);
			for (const u of docModule(name)) expect(sv).toContain(u);
		});

	test("demo/state CounterCtl is the §7.1 full file", async () => {
		const full = docSv.find(
			(b) =>
				b.startsWith("// Generated by autowire fsm (CounterCtl)") &&
				b.includes("endmodule"),
		);
		expect((await compileDemo("fsm/counter_ctl.mjs")).sv).toBe(full ?? "");
	});

	const demos: [string, string[]][] = [
		["loop_ctl", ["burst_ctl", "scan_ctl"]],
		["reg_ctl", ["reg_demo"]],
		["msg_ctl", ["msg_fwd"]],
		["phy_ctl", ["phy_init", "phy_mon"]],
		["dump_check", ["dump_check"]],
		["dump_svc", ["dump_server", "dump_client"]],
		["cfg_load", ["cfg_load"]],
		["reg_mgr", ["reg_mgr", "reg_mgr_reg"]],
		["escape_ctl", ["work_ctl", "soft_rst_ctl", "err_ctl"]],
		["cmd_ctl", ["cmd"]],
	];
	for (const [file, names] of demos)
		test(`demo/state/fsm/${file}.mjs carries the doc modules`, async () => {
			const sv = (await compileDemo(`fsm/${file}.mjs`)).sv;
			for (const n of names)
				for (const u of docModule(n)) expect(sv).toContain(u);
		});
});

test("plugin fsm run writes plugins_dir/fsm and is incremental", async () => {
	const ws = mkdtempSync(join(tmpdir(), "aw-fsm-ws-"));
	try {
		cpSync(join(demo, "autowire.toml"), join(ws, "autowire.toml"));
		cpSync(join(demo, "fsm"), join(ws, "fsm"), { recursive: true });
		const run = () =>
			Bun.spawnSync({
				cmd: [
					"bun",
					join(root, "index.ts"),
					"plugin",
					"fsm",
					"run",
					"--workspace",
					ws,
				],
				stdout: "pipe",
				stderr: "pipe",
			});
		const first = run();
		expect(first.exitCode, first.stderr.toString()).toBe(0);
		const out = join(ws, "gen/plugins/fsm");
		const counter = await compileDemo("fsm/counter_ctl.mjs");
		expect(readFileSync(join(out, "CounterCtl.sv"), "utf8")).toBe(counter.sv);
		readFileSync(join(ws, ".autowire/dsl/fsm/dsl.mjs"));
		expect(run().stdout.toString()).toContain("fsm: outputs unchanged");
	} finally {
		rmSync(ws, { recursive: true, force: true });
	}
}, 60_000);

test("[plugins.fsm] dir moves the fsm output into the RTL tree", () => {
	const ws = mkdtempSync(join(tmpdir(), "aw-fsm-dir-"));
	try {
		const toml = readFileSync(join(demo, "autowire.toml"), "utf8");
		writeFileSync(
			join(ws, "autowire.toml"),
			`${toml}\n[plugins.fsm]\ndir = "rtl/fsm"\n`,
		);
		cpSync(join(demo, "fsm"), join(ws, "fsm"), { recursive: true });
		const r = Bun.spawnSync({
			cmd: [
				"bun",
				join(root, "index.ts"),
				"plugin",
				"fsm",
				"run",
				"--workspace",
				ws,
			],
			stdout: "pipe",
			stderr: "pipe",
		});
		expect(r.exitCode, r.stderr.toString()).toBe(0);
		expect(existsSync(join(ws, "rtl/fsm/CmdCtl.sv"))).toBe(true);
		expect(existsSync(join(ws, "gen/plugins/fsm"))).toBe(false);
	} finally {
		rmSync(ws, { recursive: true, force: true });
	}
}, 60_000);

test("@FsmGroup({ file }) names the output; two groups on one stem fail", () => {
	const ws = mkdtempSync(join(tmpdir(), "aw-fsm-file-"));
	const run = () =>
		Bun.spawnSync({
			cmd: [
				"bun",
				join(root, "index.ts"),
				"plugin",
				"fsm",
				"run",
				"--workspace",
				ws,
			],
			stdout: "pipe",
			stderr: "pipe",
		});
	try {
		cpSync(join(demo, "autowire.toml"), join(ws, "autowire.toml"));
		cpSync(join(demo, "fsm"), join(ws, "fsm"), { recursive: true });
		const cmd = join(ws, "fsm/cmd_ctl.mjs");
		const text = readFileSync(cmd, "utf8");
		const named = (stem: string) =>
			writeFileSync(
				cmd,
				text.replace(
					"@FsmGroup\nexport class CmdCtl",
					`@FsmGroup({ file: "${stem}" })\nexport class CmdCtl`,
				),
			);
		named("cmd_ctl");
		const ok = run();
		expect(ok.exitCode, ok.stderr.toString()).toBe(0);
		const out = join(ws, "gen/plugins/fsm");
		expect(existsSync(join(out, "cmd_ctl.sv"))).toBe(true);
		expect(existsSync(join(out, "CmdCtl.sv"))).toBe(false);
		named("counterctl");
		const bad = run();
		expect(bad.exitCode).not.toBe(0);
		expect(bad.stderr.toString()).toContain("both write");
	} finally {
		rmSync(ws, { recursive: true, force: true });
	}
}, 60_000);

test("an action only on the self-loop S -> S is driven by action.keep_S", async () => {
	const sv = await compileBody(`@Fsm
async keep_ctl({
  go = Input(1),
  again = Input(1),
  a = Output(1),
  b = Output(1),
}) {
  while (true) {
    IDLE: await go.wait(1);
    b.pulse();
    while (true) {
      Run: await go.wait(0);
      if (again) {
        a.pulse();
        continue;
      }
      break;
    }
  }
}`);
	expect(sv).toContain("    logic keep_RUN;\n");
	expect(sv).toMatch(/assign a = action\.keep_RUN;/);
	expect(sv).toMatch(/assign b = action\.leave_IDLE;/);
	expect(sv).not.toContain("RUN_to_RUN");
});

test("a sync group method inlines its actions into the calling segment, no state", async () => {
	const sv = await compileBody(`@Fsm
async h({
  go = Input(1),
  a = Dff(1),
  b = Dff(4),
}) {
  while (true) {
    IDLE: await go.wait(1);
    this.clr({ a, b });
    RUN: await go.wait(0);
    a.set(1);
  }
}
clr({
  a = Dff(1),
  b = Dff(4),
}) {
  a.set(0);
  b.set(0);
}`);
	// Two states only: the call adds none; a is cleared on entering RUN, set on leaving it.
	expect(sv).toMatch(/typedef enum logic \[0:0\] \{\n {4}IDLE,\n {4}RUN\n/);
	expect(sv).toContain(
		"      unique case (1'b1)\n        action.enter_RUN:  a <= 1'b0;\n        action.enter_IDLE: a <= 1'b1;\n",
	);
	expect(sv).toContain(
		"    end else if (action.enter_RUN) begin\n      b <= 4'h0;\n",
	);
});

test("@Fsm({ pkg }) puts the state enum and action struct into another file's @SvEnum package", () => {
	const ws = mkdtempSync(join(tmpdir(), "aw-fsm-pkg-"));
	const dsl = 'from "../.autowire/dsl/fsm/dsl.mjs";';
	const ctl = (
		second: string,
	) => `import { FsmGroup, Fsm, Input, Output } ${dsl}
import { Op } from "./types.mjs";
@FsmGroup
export class Ctl {
  @Fsm({ pkg: "t_pkg", statePrefix: "C" })
  async c({
    go = Input(1),
    op = Output(Op),
  }) {
    while (true) {
      IDLE: await go.wait(1);
      op.pulse(Op.B);
      RUN: await go.wait(0);
    }
  }
${second}
}
`;
	const run = () =>
		Bun.spawnSync({
			cmd: [
				"bun",
				join(root, "index.ts"),
				"plugin",
				"fsm",
				"run",
				"--workspace",
				ws,
			],
			stdout: "pipe",
			stderr: "pipe",
		});
	try {
		const toml = (split: string) =>
			writeFileSync(
				join(ws, "autowire.toml"),
				`[workspace]\nname = "p"\n\n[workspace.dump]\nplugins_dir = "gen/plugins"\n\n[fsm.types]\nmjs = "fsm/types.mjs"\n\n[fsm.ctl]\nmjs = "fsm/ctl.mjs"\n${split}`,
			);
		toml("");
		mkdirSync(join(ws, "fsm"));
		writeFileSync(
			join(ws, "fsm/types.mjs"),
			`import { FsmGroup, SvEnum } ${dsl}
@SvEnum({ pkg: "t_pkg", name: "op_e", prefix: "OP" })
export class Op { static A = 0; static B = 1; }
@FsmGroup({ file: "t_pkg" })
export class T {}
`,
		);
		writeFileSync(join(ws, "fsm/ctl.mjs"), ctl(""));
		const ok = run();
		expect(ok.exitCode, ok.stderr.toString()).toBe(0);
		const out = join(ws, "gen/plugins/fsm");
		expect(readFileSync(join(out, "t_pkg.sv"), "utf8")).toContain(
			"  } op_e;\n\n  // c: state enum and action struct\n  typedef enum logic [0:0] {\n    C_IDLE,\n    C_RUN\n  } c_state_e;\n",
		);
		const sv = readFileSync(join(out, "Ctl.sv"), "utf8");
		expect(sv).toContain("module c\n  import t_pkg::*;\n");
		expect(sv).not.toContain("package c_pkg;");
		// split = true: one file per module, each with its own header.
		toml("split = true\n");
		writeFileSync(
			join(ws, "fsm/ctl.mjs"),
			ctl(
				'  @Fsm({ statePrefix: "E" })\n  async e({\n    go = Input(1),\n    op = Output(Op),\n  }) {\n    while (true) {\n      IDLE: await go.wait(1);\n      op.pulse(Op.A);\n      RUN: await go.wait(0);\n    }\n  }',
			),
		);
		const parts = run();
		expect(parts.exitCode, parts.stderr.toString()).toBe(0);
		const c = readFileSync(join(out, "c.sv"), "utf8");
		const e = readFileSync(join(out, "e.sv"), "utf8");
		expect(c).toStartWith("// Generated by autowire fsm (Ctl).");
		expect(c).toContain("module c\n");
		expect(c).not.toContain("module e\n");
		expect(e).toContain("package e_pkg;");
		expect(e).toContain("module e\n  import e_pkg::*;\n");
		// A second machine with the same prefix collides in the shared package.
		writeFileSync(
			join(ws, "fsm/ctl.mjs"),
			ctl(
				'  @Fsm({ pkg: "t_pkg", statePrefix: "C" })\n  async d({\n    go = Input(1),\n    op = Output(Op),\n  }) {\n    while (true) {\n      IDLE: await go.wait(1);\n      op.pulse(Op.A);\n      RUN: await go.wait(0);\n    }\n  }',
			),
		);
		const bad = run();
		expect(bad.exitCode).not.toBe(0);
		expect(bad.stderr.toString()).toContain("declares C_IDLE twice (c and d)");
	} finally {
		rmSync(ws, { recursive: true, force: true });
	}
}, 60_000);
