// scripts/build-js.ts sets this with --define. It is absent when the
// TypeScript sources run, and the bundler replaces it with `true` so the
// repo-read branch is stripped from autowire.js. Packaged JS must never open
// a checkout's docs/ tree.
declare const AUTOWIRE_BUNDLED: true | undefined;

export async function loadBusDef(
	tsPath: string,
	exportName: string,
): Promise<BusDef> {
	const abs = resolve(tsPath);
	const mod = (await import(pathToFileURL(abs).href)) as Record<
		string,
		unknown
	>;
	const v = mod[exportName];
	if (v === undefined) {
		throw new Error(`wishbone: export "${exportName}" not found in ${abs}`);
	}
	if (!isBusDef(v)) {
		throw new Error(`wishbone: export "${exportName}" is not a BusDef`);
	}
	if (v.name !== exportName) {
		throw new Error(
			`wishbone: BusDef.name "${v.name}" must equal export "${exportName}"`,
		);
	}
	return v;
}

export const PIPE_MODULE = "wb_cfg_pipe";

/** Git checkout reads docs/plugins/rtl. The published bundle reads the pack. */
async function templateBytes(template: string): Promise<Uint8Array> {
	if (typeof AUTOWIRE_BUNDLED === "undefined") {
		const live = join(import.meta.dir, "..", "..", "..", template);
		const file = Bun.file(live);
		if (!(await file.exists()))
			throw new Error(`wishbone: template missing from repo: ${template}`);
		return file.bytes();
	}
	const pack = await loadPack();
	const entry = pack.find((f) => f.path === template);
	if (!entry)
		throw new Error(`wishbone: template missing from docs pack: ${template}`);
	return entry.bytes;
}

async function writeTemplateModule(
	outDir: string,
	mod: string,
	force = false,
): Promise<string | null> {
	const template = `docs/plugins/rtl/${mod}_template.sv`;
	const outPath = join(outDir, `${mod}.sv`);
	const body =
		`// Generated by autowire plugin wishbone (${mod}). Do not edit.\n` +
		`// Template: ${template}\n` +
		new TextDecoder().decode(await templateBytes(template));
	return (await writeIfChanged(outPath, body, force)) ? outPath : null;
}

export async function generatePipeModule(
	outDir: string,
	force = false,
): Promise<string | null> {
	return writeTemplateModule(outDir, PIPE_MODULE, force);
}

/** Shared master-face modules (sync cell, async FIFO, CDC, APB / JTAG bridges). */
export async function generateMasterModules(
	outDir: string,
	force = false,
): Promise<string[]> {
	const paths: string[] = [];
	for (const mod of MASTER_MODULES) {
		const path = await writeTemplateModule(outDir, mod, force);
		if (path) paths.push(path);
	}
	return paths;
}

export async function generateDef(
	ws: WorkspaceConfig,
	def: BusDef,
	force = false,
): Promise<string[]> {
	const sv = emitBusSv(def);
	const outDir = ws.wishboneBusDir;
	await mkdir(outDir, { recursive: true });
	const paths: string[] = [];
	const outPath = join(outDir, `${busModuleName(def)}.sv`);
	if (await writeIfChanged(outPath, sv, force)) paths.push(outPath);
	const wrap = emitBusSystemSv(def, {
		portAlign: ws.stylePortAlign,
		paramAlign: ws.styleParamAlign,
		instPortAlign: ws.styleInstPortAlign,
		instParamAlign: ws.styleInstParamAlign,
		instPortDir: ws.styleInstPortDir,
		instPortDirFormat: ws.styleInstPortDirFormat,
		instPortWidth: ws.styleInstPortWidth,
		signalAlign: ws.styleSignalAlign,
		netType: ws.styleNetType,
	});
	if (wrap) {
		const wrapPath = join(outDir, `${busSystemModuleName(def)}.sv`);
		if (await writeIfChanged(wrapPath, wrap, force)) paths.push(wrapPath);
	}
	const icl = emitBusIcl(def);
	const pdl = emitBusPdl(def);
	if (icl && pdl) {
		const stem = join(outDir, busSystemModuleName(def));
		if (await writeIfChanged(`${stem}.icl`, icl, force))
			paths.push(`${stem}.icl`);
		if (await writeIfChanged(`${stem}.pdl`, pdl, force))
			paths.push(`${stem}.pdl`);
	}
	return paths;
}
