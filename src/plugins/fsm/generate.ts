// `plugin fsm run`: compile every [fsm.<id>] mjs= source into
// plugins_dir/fsm/<Group>.sv plus the shared aw_dff.sv (docs/state/async-fsm.md §11).

import { mkdir, readFile } from "node:fs/promises";
import { join, relative, sep } from "node:path";
import type { Node } from "@babel/types";
import { writeIfChanged } from "../../core/write.ts";
import type { WorkspaceConfig } from "../../workspace.ts";
import { BodyCompiler, type Callees } from "./cfg.ts";
import { emitGroup } from "./emit.ts";
import { type FsmMethod, parseGroup } from "./front.ts";
import { lower } from "./lower.ts";
import type { Fsm } from "./model.ts";
import { Src } from "./source.ts";

/** Every `this.name(...)` call under `node`, in source order. */
function thisCalls(node: Node): { name: string; node: Node }[] {
	const out: { name: string; node: Node }[] = [];
	const walk = (n: unknown): void => {
		if (Array.isArray(n)) {
			for (const c of n) walk(c);
			return;
		}
		if (!n || typeof n !== "object" || !("type" in n)) return;
		const x = n as Node;
		if (
			x.type === "CallExpression" &&
			x.callee.type === "MemberExpression" &&
			x.callee.object.type === "ThisExpression" &&
			x.callee.property.type === "Identifier"
		)
			out.push({ name: x.callee.property.name, node: x });
		for (const [k, v] of Object.entries(x))
			if (
				k !== "loc" &&
				k !== "leadingComments" &&
				k !== "trailingComments" &&
				k !== "innerComments"
			)
				walk(v);
	};
	walk(node);
	return out;
}

export const AW_DFF_SV = `// Generated by autowire fsm. Do not edit: reference DFF of docs/state/async-fsm.md §6.5.
module aw_dff #(parameter type T = logic, parameter T RST = T'(0)) (
  input  logic clk, rst_n,
  input  logic set,
  input  T     next,
  output T     val
);
  always_ff @(posedge clk or negedge rst_n)
    if (!rst_n)   val <= RST;
    else if (set) val <= next;
endmodule
`;

export interface CompiledGroup {
	/** @FsmGroup class name: the output file stem. */
	name: string;
	sv: string;
}

/** Compile one DSL source. `file` is workspace-relative (errors, file header);
 *  `dsl` is the absolute path builtins must be imported from. */
export async function compileFsmSource(o: {
	file: string;
	abs: string;
	text: string;
	dsl: string;
}): Promise<CompiledGroup> {
	const src: Src = new Src(o.file, o.text);
	const g = await parseGroup(src, { abs: o.abs, dsl: o.dsl });
	const byName = new Map(g.methods.map((m) => [m.name, m]));
	const callees: Callees = new Map(
		g.methods.filter((m) => !m.sub).map((m) => [m.name, null]),
	);
	const compiled = new Map<string, Fsm>();
	const state = new Map<string, "busy" | "done">();
	// Depth-first: a sub-FSM's shape (ports, result width) is known before any caller compiles.
	const visit = (m: FsmMethod) => {
		if (state.get(m.name) === "done") return;
		state.set(m.name, "busy");
		for (const c of thisCalls(m.node.body)) {
			const callee = byName.get(c.name);
			if (!callee) src.fail(c.node, `no method ${c.name} in this @FsmGroup`);
			if (!callee.sub)
				src.fail(
					c.node,
					`${c.name} is an @Fsm method; only sub-FSMs can be called (§5)`,
				);
			if (state.get(c.name) === "busy")
				src.fail(c.node, `recursive sub-FSM call: ${m.name} → ${c.name}`);
			visit(callee);
		}
		const fsm = lower(
			src,
			m,
			new BodyCompiler(src, g.builtins, g.packages, callees).compile(m),
		);
		if (m.sub)
			callees.set(m.name, { ports: m.ports, resultWidth: fsm.resultWidth });
		compiled.set(m.name, fsm);
		state.set(m.name, "done");
	};
	for (const m of g.methods) if (!m.sub) visit(m);
	for (const m of g.methods)
		if (!compiled.has(m.name))
			src.fail(m.node, `sub-FSM ${m.name} is never called (§5)`);
	const fsms = g.methods.map((m) => compiled.get(m.name) as Fsm);
	return {
		name: g.name,
		sv: emitGroup({ name: g.name, comment: g.comment, fsms }, o.file),
	};
}

/** Where the materialized DSL lives (src/plugins/fsm/dsl.mjs in the pack). */
export function fsmDslPath(root: string): string {
	return join(root, ".autowire", "dsl", "fsm", "dsl.mjs");
}

export async function generateAll(
	ws: WorkspaceConfig,
	only: string | undefined,
	force: boolean,
): Promise<string[]> {
	let sources = ws.fsmSources;
	if (only) {
		sources = sources.filter((s) => s.id === only);
		if (sources.length === 0)
			throw new Error(
				`fsm: no [fsm.${only}] in autowire.toml (have: ${ws.fsmSources.map((s) => s.id).join(", ")})`,
			);
	}
	const dir = join(ws.pluginsDir, "fsm");
	const groups = new Map<string, string>();
	const outputs: { path: string; text: string }[] = [];
	for (const s of sources) {
		const file = relative(ws.root, s.mjs).split(sep).join("/");
		const text = await readFile(s.mjs, "utf8");
		const g = await compileFsmSource({
			file,
			abs: s.mjs,
			text,
			dsl: fsmDslPath(ws.root),
		});
		const prev = groups.get(g.name);
		if (prev)
			throw new Error(
				`fsm: @FsmGroup ${g.name} is defined in both ${prev} and ${file}`,
			);
		groups.set(g.name, file);
		outputs.push({ path: join(dir, `${g.name}.sv`), text: g.sv });
	}
	await mkdir(dir, { recursive: true });
	const paths: string[] = [];
	for (const o of [
		{ path: join(dir, "aw_dff.sv"), text: AW_DFF_SV },
		...outputs,
	])
		if (await writeIfChanged(o.path, o.text, force)) paths.push(o.path);
	return paths;
}
