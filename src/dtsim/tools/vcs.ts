// Built-in VCS backend. Everything VCS-shaped (simv, +UVM_*, fsdb, urg,
// verdi) lives here; the core engine never mentions these flags.
// toolOptions.ntbOpts picks the -ntb_opts value (default "uvm", e.g. "uvm-1.2";
// "" leaves -ntb_opts out for a non-UVM bench).
// toolOptions.flags replaces DEFAULT_FLAGS (older VCS releases reject some
// of them, e.g. O-2018.09 reads "-xlrm nettype_array" as a source file).
import { chmodSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import type { SimTool, ToolContext } from "../dsl/index.ts";

const DEFAULT_FLAGS = [
	"-xlrm",
	"nettype_array",
	"+lint=TFIPC-L",
	"-sverilog",
	"-full64",
	"+error+10000",
	"-error=noMPD",
	"-debug_acc+all",
	"-debug_region+cell+encrypt",
	"-timescale=1ns/1ps",
	"-kdb",
	"-lca",
	"+v2k",
	"-v2k_generate",
	"+transport_path_delays",
	"+pulse_e/0",
	"+pulse_r/0",
];

/** Whole ns (at least 1): UVM reads +UVM_TIMEOUT with $sscanf("%d,%s"). */
function parseTimeoutNs(value: string): string {
	const m = /^(\d+(?:\.\d+)?)(s|ms|us|ns|ps)?$/.exec(value.trim());
	if (!m) throw new Error(`dtsim: invalid uvm timeout "${value}"`);
	const scale: Record<string, number> = {
		s: 1e9,
		ms: 1e6,
		us: 1e3,
		ns: 1,
		ps: 0.001,
	};
	const unit = m[2] ?? "ns";
	return String(Math.max(1, Math.ceil(Number(m[1]) * (scale[unit] ?? 1))));
}

function ntbOpts(opts: Record<string, unknown>): string {
	return typeof opts.ntbOpts === "string" ? opts.ntbOpts : "uvm";
}

function compileFlags(opts: Record<string, unknown>): string[] {
	const flags = opts.flags;
	if (flags === undefined) return DEFAULT_FLAGS;
	if (!Array.isArray(flags) || flags.some((f) => typeof f !== "string")) {
		throw new Error("dtsim: vcs toolOptions.flags must be a string array");
	}
	return flags;
}

function dumpTcl(ctx: ToolContext): string {
	const en = ctx.wave.enabled ? 1 : 0;
	const { depth, top } = ctx.wave;
	return `set dump_enable ${en}
if { $dump_enable } {
    fsdbDumpfile verilog.fsdb
    fsdbDumpvars ${depth} ${top} "+all"
    fsdbDumpSVA
    fsdbDumpon
    run
} else {
    # waveform disabled (--no-wave): same command shape, dump ops skipped
    run
}
`;
}

function verdiScript(ctx: ToolContext): string {
	return `#!/bin/bash
# run_verdi -- generated by dtsim (VCS backend).
TOP=""
while [[ $# -gt 0 ]]; do
  case "$1" in
    -t) TOP="-top tb_top"; shift ;;
    *) shift ;;
  esac
done
verdi -sv -f ${ctx.filelist} -ssf ${join(ctx.dir, "verilog.fsdb")} ${ctx.caseOpts.defines
		.map((d) => `+define+${d}`)
		.join(" ")} $TOP &
`;
}

export const vcsTool: SimTool = {
	kind: "dtsim-tool",
	id: "vcs",
	interactive: true,
	passthrough: [
		"PATH",
		"HOME",
		"USER",
		"LOGNAME",
		"LANG",
		"LC_ALL",
		"TMPDIR",
		"TMP",
		"TEMP",
		"LD_LIBRARY_PATH",
		"VCS_HOME",
		"VERDI_HOME",
		"VC_STATIC_HOME",
		"SYNOPSYS",
		"UVM_HOME",
		"DESIGNWARE_HOME",
		"LM_LICENSE_FILE",
		"SNPSLMD_LICENSE_FILE",
	],
	compileErrors: [/Error-\[/, /^Error:/, /^\*E,/],
	simErrors: [/UVM_ERROR/, /UVM_FATAL/, /Error-\[/, /^Error:/],

	// simv depends on the -ntb_opts library and the compile flag set too.
	compileKey(c, base) {
		return JSON.stringify([
			base,
			ntbOpts(c.toolOptions),
			compileFlags(c.toolOptions),
		]);
	},

	writeAux(ctx) {
		if (ctx.phase === "compile") {
			writeFileSync(join(ctx.dir, "dump.tcl"), dumpTcl(ctx));
			if (ctx.cov.enabled) {
				const viewer = join(ctx.dir, "verdi_cov");
				writeFileSync(
					viewer,
					`#!/bin/bash\nif [ -d merge.vdb ]; then db=merge.vdb; else db=simv.vdb; fi\nverdi -cov -covdir "$db" &\n`,
				);
				chmodSync(viewer, 0o755);
			}
		} else {
			const script = join(ctx.dir, "run_verdi");
			writeFileSync(script, verdiScript(ctx));
			chmodSync(script, 0o755);
		}
	},

	compile(ctx) {
		const argv = [
			"vcs",
			...compileFlags(ctx.caseOpts.toolOptions),
			...(ntbOpts(ctx.caseOpts.toolOptions)
				? ["-ntb_opts", ntbOpts(ctx.caseOpts.toolOptions)]
				: []),
			"-f",
			ctx.filelist,
			"-l",
			join(ctx.dir, "vcs.log"),
			...ctx.caseOpts.defines.map((d) => `+define+${d}`),
			...ctx.caseOpts.compileArgs,
			...(ctx.cov.enabled
				? ["-cm", ctx.cov.metrics, "-cm_dir", join(ctx.dir, "simv.vdb")]
				: []),
		].map((a) => ctx.expand(a));
		return {
			argv,
			cwd: ctx.dir,
			log: join(ctx.dir, "vcs.log"),
			logMode: "tool",
			executable: join(ctx.dir, "simv"),
		};
	},

	simulate(ctx) {
		const uvm = ctx.caseOpts.uvm;
		const simv = ctx.regression ? join(ctx.compileDir, "simv") : "../simv";
		const argv = [
			simv,
			"-ucli",
			"-i",
			join(ctx.compileDir, "dump.tcl"),
			"-l",
			join(ctx.dir, "sim.log"),
			`+TEST=${ctx.caseId}`,
			"+vcs+lic+wait",
		];
		if (uvm) {
			argv.push(
				`+UVM_TESTNAME=${uvm.test ?? "top_test"}`,
				`+UVM_VERBOSITY=${uvm.verbosity ?? "UVM_HIGH"}`,
				`+UVM_MAX_QUIT_COUNT=${uvm.maxQuit ?? 9999}`,
				// argv, not a shell line: quotes would reach UVM, whose "%d"
				// then reads 0 and every test dies of PH_TIMEOUT at time 0.
				`+UVM_TIMEOUT=${parseTimeoutNs(uvm.timeout ?? "1000ps")},YES`,
				`+test_drain_time=${uvm.drainTime ?? 100}`,
			);
			if (uvm.seq) argv.push(`+user_seq_type=${uvm.seq}`);
		}
		argv.push(...ctx.caseOpts.simArgs);
		if (ctx.cov.enabled && ctx.seed !== undefined) {
			const cmName = `${ctx.caseId}_${ctx.seed}`.replace(/[^A-Za-z0-9_]/g, "_");
			argv.push(
				"-cm",
				ctx.cov.metrics,
				"-cm_dir",
				join(ctx.compileDir, "simv.vdb"),
				"-cm_name",
				cmName,
				"-cm_log",
				join(ctx.dir, "cm.log"),
			);
		}
		return {
			argv: argv.map((a) => ctx.expand(a)),
			cwd: ctx.dir,
			log: join(ctx.dir, "sim.log"),
			logMode: "tool",
		};
	},
};
