// Filelist flattening. Entries in a dtsim filelist are relative to the project
// root (the RTL design dir that owns dt/), the same rule autowire.toml
// filelists follow. Tools run inside the compile dir, so dtsim writes one
// absolute, flat copy there and hands that to the backend.
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { isAbsolute, resolve } from "node:path";

/** Windows tools and the generated bash scripts all accept forward slashes. */
export function toolPath(path: string): string {
	return process.platform === "win32" ? path.replaceAll("\\", "/") : path;
}

function absolute(root: string, entry: string): string {
	// $VAR / ${VAR} entries are left to the tool (VCS and Verilator expand them).
	if (entry.startsWith("$") || isAbsolute(entry)) return toolPath(entry);
	return toolPath(resolve(root, entry));
}

function flattenInto(
	file: string,
	root: string,
	expand: (text: string) => string,
	stack: string[],
	out: string[],
): void {
	if (stack.includes(file)) {
		throw new Error(
			`dtsim: filelist cycle: ${[...stack, file].map(toolPath).join(" -> ")}`,
		);
	}
	if (!existsSync(file)) {
		const from = stack.at(-1);
		throw new Error(
			`dtsim: filelist not found: ${toolPath(file)}${from ? ` (from ${toolPath(from)})` : ""}`,
		);
	}
	stack.push(file);
	for (const raw of readFileSync(file, "utf8").split(/\r?\n/)) {
		const line = expand(raw.trim());
		if (line.length === 0 || line.startsWith("#") || line.startsWith("//"))
			continue;
		const tokens = line.split(/\s+/);
		for (let i = 0; i < tokens.length; i++) {
			const tok = tokens[i] as string;
			if (tok === "-f" || tok === "-F") {
				const next = tokens[++i];
				if (next === undefined)
					throw new Error(`dtsim: ${toolPath(file)}: ${tok} without a path`);
				flattenInto(resolve(root, next), root, expand, stack, out);
			} else if (tok === "-v" || tok === "-y") {
				const next = tokens[++i];
				if (next === undefined)
					throw new Error(`dtsim: ${toolPath(file)}: ${tok} without a path`);
				out.push(`${tok} ${absolute(root, next)}`);
			} else if (tok.startsWith("+incdir+")) {
				const dirs = tok.slice("+incdir+".length).split("+").filter(Boolean);
				out.push(`+incdir+${dirs.map((d) => absolute(root, d)).join("+")}`);
			} else if (tok.startsWith("-") || tok.startsWith("+")) {
				out.push(tok);
			} else {
				out.push(absolute(root, tok));
			}
		}
	}
	stack.pop();
}

/** Flatten `source` (nested -f inlined, paths absolute) and write it to `target`. */
export function writeFlatFilelist(
	source: string,
	target: string,
	root: string,
	expand: (text: string) => string,
): void {
	const out: string[] = [];
	flattenInto(source, root, expand, [], out);
	writeFileSync(
		target,
		`# Generated by dtsim from ${toolPath(source)}; paths resolved against ${toolPath(root)}.\n${out.join("\n")}\n`,
	);
}
