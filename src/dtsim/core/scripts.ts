// Generated artifacts: run_sim, dresults, git_rev, result markers, timing.
import { spawnSync } from "node:child_process";
import { chmodSync, rmSync, symlinkSync, writeFileSync } from "node:fs";
import { join } from "node:path";

function shellQuote(value: string): string {
	return `'${value.replace(/'/g, `'\\''`)}'`;
}

/** run_sim runs under MSYS bash on Windows: `export PATH=` must use the
 *  MSYS form (`/c/x:/d/y`); the Windows form breaks every command lookup. */
function exportValue(key: string, value: string): string {
	if (process.platform !== "win32" || key.toUpperCase() !== "PATH")
		return value;
	return value
		.split(";")
		.filter(Boolean)
		.map((p) =>
			p
				.replaceAll("\\", "/")
				.replace(/^([A-Za-z]):/, (_m, d: string) => `/${d.toLowerCase()}`),
		)
		.join(":");
}

/**
 * run_sim re-runs exactly what dtsim ran, including the resolved case env
 * and injected variables. -s <seed> overrides the seed at runtime.
 * Timestamps are written around the sim command so elapsed time excludes
 * any cluster queue wait.
 */
export function writeRunSim(args: {
	dir: string;
	seed: string;
	exports: Record<string, string>;
	argv: string[];
}): string {
	const lines = [
		"#!/bin/bash",
		"# run_sim -- generated by dtsim; do not edit.",
		...Object.entries(args.exports).map(
			([k, v]) => `export ${k}=${shellQuote(exportValue(k, v))}`,
		),
		`SEED=${shellQuote(args.seed)}`,
		"while [[ $# -gt 0 ]]; do",
		'  case "$1" in',
		'    -s) SEED="$2"; shift 2 ;;',
		"    *) shift ;;",
		"  esac",
		"done",
		"date +%s > .start_time",
		`${args.argv.map(shellQuote).join(" ")} +ntb_random_seed=$SEED`,
		"rc=$?",
		"date +%s > .end_time",
		"exit $rc",
		"",
	];
	const path = join(args.dir, "run_sim");
	writeFileSync(path, lines.join("\n"));
	chmodSync(path, 0o755);
	return path;
}

export function writeResultMarker(dir: string, status: string): void {
	rmSync(join(dir, ".result"), { force: true });
	try {
		symlinkSync(status, join(dir, ".result"));
	} catch {
		// A dangling link from a previous run must not fail the grade.
	}
	writeFileSync(join(dir, status), "");
}

/** Short hash plus dirty marker of the repo holding `repo` (the dt/config
 *  dir, i.e. the testbench); silently skipped outside a git repo. */
export function writeGitRev(dir: string, repo: string): void {
	const hash = spawnSync("git", ["rev-parse", "--short", "HEAD"], {
		cwd: repo,
		encoding: "utf8",
		timeout: 5000,
	});
	if (hash.status !== 0) return;
	const dirty = spawnSync("git", ["diff-index", "--quiet", "HEAD", "--"], {
		cwd: repo,
		timeout: 5000,
	});
	const stamp = new Date().toISOString().replace("T", " ").slice(0, 19);
	const suffix = dirty.status === 0 ? "" : "-dirty";
	writeFileSync(
		join(dir, "git_rev"),
		`${hash.stdout.trim()}${suffix}\n${stamp}\n`,
	);
}

export function fmtElapsed(seconds: number): string {
	const total = Math.max(0, Math.round(seconds));
	const h = Math.floor(total / 3600);
	const m = Math.floor((total % 3600) / 60);
	const s = total % 60;
	const mm = String(m).padStart(2, "0");
	const ss = String(s).padStart(2, "0");
	return h > 0 ? `${h}:${mm}:${ss}` : `${mm}:${ss}`;
}

export function timingLines(t0: number): string[] {
	const fmt = (t: number): string =>
		new Date(t).toISOString().replace("T", " ").slice(0, 19);
	return [
		`Start time : ${fmt(t0)}`,
		`End time   : ${fmt(Date.now())}`,
		`Elapsed    : ${fmtElapsed((Date.now() - t0) / 1000)}`,
	];
}

/** Fast result viewer living in each regression root. */
export function writeDresultsScript(dir: string): string {
	const script = `#!/bin/bash
# dresults -- generated by dtsim. Fast mode reads .result links only.
if [[ "$1" == "--recheck" ]]; then
  shift
  exec \${DTSIM_BIN:-dtsim} results --dir "$(pwd)" --recheck "$@"
fi
pass=0; fail=0; pwe=0; other=0
while IFS= read -r link; do
  status=$(readlink "$link")
  case "$status" in
    "PASS") pass=$((pass+1)); color=$'\\033[32m' ;;
    "PASS WITH ERRORS") pwe=$((pwe+1)); color=$'\\033[33m' ;;
    "FAIL") fail=$((fail+1)); color=$'\\033[31m' ;;
    *) other=$((other+1)); color=$'\\033[31m' ;;
  esac
  printf "%s%-18s\\033[0m %s\\n" "$color" "$status" "$(dirname "$link")"
done < <(find . -name .result -type l | sort)
printf "PASS=%d PASS_WITH_ERRORS=%d FAIL=%d OTHER=%d\\n" "$pass" "$pwe" "$fail" "$other"
`;
	const path = join(dir, "dresults");
	writeFileSync(path, script);
	chmodSync(path, 0o755);
	return path;
}
