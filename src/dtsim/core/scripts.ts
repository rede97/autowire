// Generated artifacts: run_sim, dresults, git_rev, result markers, timing.
import { spawnSync } from "node:child_process";
import { chmodSync, rmSync, symlinkSync, writeFileSync } from "node:fs";
import { basename, join } from "node:path";

function shellQuote(value: string): string {
	return `'${value.replace(/'/g, `'\\''`)}'`;
}

/** run_sim runs under MSYS bash on Windows: `export PATH=` must use the
 *  MSYS form (`/c/x:/d/y`); the Windows form breaks every command lookup. */
function exportValue(key: string, value: string): string {
	if (process.platform !== "win32" || key.toUpperCase() !== "PATH")
		return value;
	return value
		.split(";")
		.filter(Boolean)
		.map((p) =>
			p
				.replaceAll("\\", "/")
				.replace(/^([A-Za-z]):/, (_m, d: string) => `/${d.toLowerCase()}`),
		)
		.join(":");
}

/**
 * run_sim re-runs exactly what dtsim ran, including the resolved case env
 * and injected variables. -s <seed> overrides the seed at runtime.
 * Timestamps are written around the sim command so elapsed time excludes
 * any cluster queue wait.
 */
export function writeRunSim(args: {
	dir: string;
	seed: string;
	exports: Record<string, string>;
	argv: string[];
}): string {
	const lines = [
		"#!/bin/bash",
		"# run_sim -- generated by dtsim; do not edit.",
		...Object.entries(args.exports).map(
			([k, v]) => `export ${k}=${shellQuote(exportValue(k, v))}`,
		),
		`SEED=${shellQuote(args.seed)}`,
		"while [[ $# -gt 0 ]]; do",
		'  case "$1" in',
		'    -s) SEED="$2"; shift 2 ;;',
		"    *) shift ;;",
		"  esac",
		"done",
		"date +%s > .start_time",
		`${args.argv.map(shellQuote).join(" ")} +ntb_random_seed=$SEED`,
		"rc=$?",
		"date +%s > .end_time",
		"exit $rc",
		"",
	];
	const path = join(args.dir, "run_sim");
	writeFileSync(path, lines.join("\n"));
	chmodSync(path, 0o755);
	return path;
}

/**
 * run_compile records the compile command dtsim runs: the resolved compile
 * env, the tool argv, and (as a comment) the command as submitted through
 * the launcher. dtsim does not run this file; it is there to read or rerun
 * by hand.
 */
export function writeRunCompile(args: {
	dir: string;
	cwd: string;
	exports: Record<string, string>;
	argv: readonly string[];
	submitted: readonly string[];
}): string {
	const lines = [
		"#!/bin/bash",
		"# run_compile -- generated by dtsim; a record, dtsim runs the command itself.",
		`# submitted: ${args.submitted.map(shellQuote).join(" ")}`,
		...Object.entries(args.exports).map(
			([k, v]) => `export ${k}=${shellQuote(exportValue(k, v))}`,
		),
		`cd ${shellQuote(args.cwd)} || exit 1`,
		`exec ${args.argv.map(shellQuote).join(" ")}`,
		"",
	];
	const path = join(args.dir, "run_compile");
	writeFileSync(path, lines.join("\n"));
	chmodSync(path, 0o755);
	return path;
}

export function writeResultMarker(dir: string, status: string): void {
	rmSync(join(dir, ".result"), { force: true });
	try {
		symlinkSync(status, join(dir, ".result"));
	} catch {
		// A dangling link from a previous run must not fail the grade.
	}
	writeFileSync(join(dir, status), "");
}

/** Short hash plus dirty marker of the repo holding `repo` (the dt/config
 *  dir, i.e. the testbench); silently skipped outside a git repo. */
export function writeGitRev(dir: string, repo: string): void {
	const hash = spawnSync("git", ["rev-parse", "--short", "HEAD"], {
		cwd: repo,
		encoding: "utf8",
		timeout: 5000,
	});
	if (hash.status !== 0) return;
	const dirty = spawnSync("git", ["diff-index", "--quiet", "HEAD", "--"], {
		cwd: repo,
		timeout: 5000,
	});
	const stamp = new Date().toISOString().replace("T", " ").slice(0, 19);
	const suffix = dirty.status === 0 ? "" : "-dirty";
	writeFileSync(
		join(dir, "git_rev"),
		`${hash.stdout.trim()}${suffix}\n${stamp}\n`,
	);
}

export function fmtElapsed(seconds: number): string {
	const total = Math.max(0, Math.round(seconds));
	const h = Math.floor(total / 3600);
	const m = Math.floor((total % 3600) / 60);
	const s = total % 60;
	const mm = String(m).padStart(2, "0");
	const ss = String(s).padStart(2, "0");
	return h > 0 ? `${h}:${mm}:${ss}` : `${mm}:${ss}`;
}

/** "elapsed 00:37 (2026-11-18 09:46:09 → 09:46:46)" for the end of a run. */
export function elapsedLine(t0: number): string {
	const fmt = (t: number): string =>
		new Date(t).toISOString().replace("T", " ").slice(0, 19);
	const end = fmt(Date.now());
	return `elapsed ${fmtElapsed((Date.now() - t0) / 1000)} (${fmt(t0)} → ${end.slice(11)})`;
}

/**
 * argv that re-enters this dtsim: `bun <entry> dtsim` for index.ts or
 * autowire.js, `<binary> dtsim` for the compiled autowire, and no `dtsim`
 * word for a binary named dtsim. Windows paths use `/` so MSYS bash runs them.
 */
function selfCommand(): string[] {
	const exe = process.execPath;
	const viaBun = /^bun(\.exe)?$/i.test(basename(exe));
	const cmd = viaBun ? [exe, Bun.main, "dtsim"] : [exe, "dtsim"];
	if (!viaBun && /^dtsim(\.exe)?$/i.test(basename(exe))) cmd.pop();
	return process.platform === "win32"
		? cmd.map((p) => p.replaceAll("\\", "/"))
		: cmd;
}

/** `dresults` in each regression root: `dtsim results --dir <that root>`,
 *  arguments passed through (`--recheck`, `--csv`). `$DTSIM_BIN` replaces
 *  the recorded command, e.g. after the tree moved to another machine. */
export function writeDresultsScript(dir: string): string {
	const self = selfCommand().map(shellQuote).join(" ");
	const script = `#!/bin/bash
# dresults -- generated by dtsim; forwards to \`dtsim results\`.
here=$(cd "$(dirname "$0")" && pwd)
# --recheck finds dt/config/dtsim.config.ts upward from the regression root.
cd "$here" || exit 1
if [[ -n "\${DTSIM_BIN:-}" ]]; then
  exec "$DTSIM_BIN" results --dir "$here" "$@"
fi
exec ${self} results --dir "$here" "$@"
`;
	const path = join(dir, "dresults");
	writeFileSync(path, script);
	chmodSync(path, 0o755);
	return path;
}
