// Result grading. Status comes from the log content, never from the
// simulator exit code. The generated check_result.js embeds the exact same
// functions via toString(), so the two cannot drift apart.
import { readFileSync } from "node:fs";
import type { GradeSpec, WaiveRuleDef } from "../dsl/index.ts";

export type GradeStatus =
	| "PASS"
	| "PASS WITH ERRORS"
	| "FAIL"
	| "NO SIM LOG"
	| "ABORTED";

export type WaiveOutcome = {
	kept: string[];
	waived: number;
	unclosed: boolean;
	unknown: string[];
};

/** Substring by default; "re:" prefix for regex; invalid regex = substring. */
export function kwMatchLine(kw: string, line: string): boolean {
	if (kw.startsWith("re:")) {
		const pat = kw.slice(3);
		try {
			return new RegExp(pat).test(line);
		} catch {
			return line.includes(pat);
		}
	}
	return line.includes(kw);
}

/**
 * Drop lines waived by DSIM_WAIVE_* markers. Marker lines are never kept:
 * their own text usually contains the error pattern. Named rules switch on
 * DSIM_WAIVE_ON (replace set) and off with DSIM_WAIVE_OFF; inline regions
 * run from DSIM_WAIVE_BEGIN [pattern] to DSIM_WAIVE_END, and an unclosed
 * region extends to EOF.
 */
export function applyWaiveRegions(
	lines: string[],
	rules: Record<string, string>,
): WaiveOutcome {
	const kept: string[] = [];
	let waived = 0;
	let inRegion = false;
	let regionPat = "";
	let active = new Set<string>();
	const unknown = new Set<string>();
	for (const line of lines) {
		if (line.includes("DSIM_WAIVE_ON")) {
			const names =
				line.split("DSIM_WAIVE_ON", 2)[1]?.trim().split(/\s+/) ?? [];
			active = new Set(names.filter((n) => n.length > 0));
			for (const n of active) {
				if (rules[n] === undefined) unknown.add(n);
			}
			continue;
		}
		if (line.includes("DSIM_WAIVE_OFF")) {
			active = new Set();
			continue;
		}
		if (line.includes("DSIM_WAIVE_BEGIN")) {
			inRegion = true;
			const idx = line.indexOf("DSIM_WAIVE_BEGIN") + "DSIM_WAIVE_BEGIN".length;
			regionPat = line.slice(idx).trim();
			continue;
		}
		if (line.includes("DSIM_WAIVE_END")) {
			inRegion = false;
			regionPat = "";
			continue;
		}
		if (inRegion && (regionPat.length === 0 || kwMatchLine(regionPat, line))) {
			waived += 1;
			continue;
		}
		let ruleHit = false;
		for (const name of active) {
			const pattern = rules[name];
			if (pattern !== undefined && kwMatchLine(pattern, line)) {
				ruleHit = true;
				break;
			}
		}
		if (ruleHit) {
			waived += 1;
			continue;
		}
		kept.push(line);
	}
	return { kept, waived, unclosed: inRegion, unknown: [...unknown].sort() };
}

export type GradeDetails = {
	status: GradeStatus;
	errorCounts: Record<string, number>;
	missingExpect: string[];
	waived: number;
	unclosed: boolean;
	unknown: string[];
	lines: string[];
	kept: string[];
};

export function gradeLines(
	lines: string[],
	spec: GradeSpec,
	rules: Record<string, string>,
): GradeDetails {
	const { kept, waived, unclosed, unknown } = applyWaiveRegions(lines, rules);
	const errorCounts: Record<string, number> = {};
	for (const kw of spec.error) {
		if (kw.length === 0) continue;
		const n = kept.filter((line) => kwMatchLine(kw, line)).length;
		if (n > 0) errorCounts[kw] = n;
	}
	const missingExpect = spec.expect.filter(
		(kw) => kw.length > 0 && !lines.some((line) => kwMatchLine(kw, line)),
	);
	const passed = spec.pass.some((kw) =>
		lines.some((line) => line.includes(kw)),
	);
	let status: GradeStatus = "PASS";
	if (!passed) status = "FAIL";
	else if (Object.keys(errorCounts).length > 0 || missingExpect.length > 0) {
		status = "PASS WITH ERRORS";
	}
	return {
		status,
		errorCounts,
		missingExpect,
		waived,
		unclosed,
		unknown,
		lines,
		kept,
	};
}

export function waiveRuleMap(
	rules: readonly WaiveRuleDef[],
): Record<string, string> {
	const out: Record<string, string> = {};
	for (const r of rules) out[r.name] = r.pattern;
	return out;
}

/** Grade an existing sim.log on disk. Missing file = NO SIM LOG. */
export function gradeLog(
	logPath: string,
	spec: GradeSpec,
	rules: Record<string, string>,
): GradeDetails {
	let text: string;
	try {
		text = readFileSync(logPath, "utf8");
	} catch {
		return {
			status: "NO SIM LOG",
			errorCounts: {},
			missingExpect: [],
			waived: 0,
			unclosed: false,
			unknown: [],
			lines: [],
			kept: [],
		};
	}
	return gradeLines(text.split("\n"), spec, rules);
}

/** Self-contained re-grade script written into every seed directory. */
export function checkResultSource(): string {
	return `#!/usr/bin/env node
// check_result.js -- re-grade sim.log. Generated by dtsim; do not edit.
const fs = require("node:fs");
const path = require("node:path");

${kwMatchLine.toString()}

${applyWaiveRegions.toString()}

function readList(file) {
	try {
		return fs.readFileSync(file, "utf8").split("\\n").filter((l) => l.length > 0);
	} catch {
		return [];
	}
}

function mark(status) {
	try {
		if (fs.existsSync(".result")) fs.unlinkSync(".result");
		fs.symlinkSync(status, ".result");
	} catch {}
	try {
		fs.writeFileSync(status, "");
	} catch {}
}

process.chdir(path.dirname(__filename));
if (!fs.existsSync("sim.log")) {
	console.log("NO SIM LOG");
	mark("NO SIM LOG");
	process.exit(2);
}
const lines = fs.readFileSync("sim.log", "utf8").split("\\n");
const rules = {};
for (const row of readList("waive_rules")) {
	const tab = row.indexOf("\\t");
	if (tab > 0) rules[row.slice(0, tab)] = row.slice(tab + 1);
}
const kept = applyWaiveRegions(lines, rules).kept;
const errors = readList("error_keywords");
const expects = readList("expect_keywords");
const pass = readList("pass_keywords");
const passWords = pass.length > 0 ? pass : ["TEST PASSED"];
let status = "PASS";
let code = 0;
if (!passWords.some((kw) => lines.some((l) => l.includes(kw)))) {
	status = "FAIL";
	code = 1;
} else if (
	errors.some((kw) => kept.some((l) => kwMatchLine(kw, l))) ||
	expects.some((kw) => !lines.some((l) => kwMatchLine(kw, l)))
) {
	status = "PASS WITH ERRORS";
}
console.log(status);
mark(status);
process.exit(code);
`;
}
