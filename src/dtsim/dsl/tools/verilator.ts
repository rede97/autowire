// Built-in Verilator backend. No UVM plusargs, no fsdb/urg: it compiles an
// executable and runs it. VerilatorTool({ mdir, main, command }); a
// case's toolOptions may override any of them. The top module is the case's
// `top` (--top-module); the executable is <mdir>/V<top>. main=false builds a
// C++ harness (--cc --exe --build; the .cpp files and --timing come from
// compileArgs) instead of --binary. The case's `wave` compiles with
// --trace-fst and binds a small dtsim_wave module into the top:
// $dumpfile("wave.fst"), $dumpvars(depth, scope), so each seed dir gets
// wave.fst without touching the bench. A C++ harness must call
// VerilatedContext::traceEverOn(true).
import { writeFileSync } from "node:fs";
import { join } from "node:path";
import type { SimTool, WaveSpec } from "../index.ts";

export type VerilatorOpts = {
	mdir?: string;
	main?: boolean;
	/** The compiler to run (default "verilator"), e.g. verilator_bin or a path. */
	command?: string;
};

type Resolved = Required<VerilatorOpts>;

function verilatorOpts(opts: Record<string, unknown>): Resolved {
	const command = opts.command ?? "verilator";
	if (typeof command !== "string" || command.length === 0) {
		throw new Error("dtsim: verilator command must be a non-empty string");
	}
	return {
		mdir: typeof opts.mdir === "string" ? opts.mdir : "obj_dir",
		main: opts.main !== false,
		command,
	};
}

/** Forward slashes on Windows: make (verilator --build) and the generated
 *  scripts take them; backslashes do not survive make. */
function slash(path: string): string {
	return process.platform === "win32" ? path.replaceAll("\\", "/") : path;
}

/** The dump module, bound into the top; it dumps the wave scope. */
function waveModule(top: string, wave: WaveSpec): string {
	return `// generated by dtsim (Verilator backend, wave on)
module dtsim_wave;
  initial begin
    $dumpfile("wave.fst");
    $dumpvars(${wave.depth}, ${wave.scope});
  end
endmodule
bind ${top} dtsim_wave dtsim_wave_i();
`;
}

export function VerilatorTool(opts: VerilatorOpts = {}): SimTool {
	const resolved = (caseOpts: Record<string, unknown>) =>
		verilatorOpts({ ...opts, ...caseOpts });
	verilatorOpts(opts);
	return {
		kind: "dtsim-tool",
		name: "verilator",
		probe: ["verilator"],
		interactive: false,
		passthrough: [
			"PATH",
			"HOME",
			"USER",
			"LANG",
			"LC_ALL",
			"TMPDIR",
			"LD_LIBRARY_PATH",
			"VERILATOR_ROOT",
			"CC",
			"CXX",
			"SYSTEMC_INCLUDE",
			"SYSTEMC_LIBDIR",
		],
		compileErrors: [/%Error/, /%Fatal/],
		simErrors: [/%Error/, /%Fatal/],
		// Verilator reads its own seed plusarg (a C++ harness must pass argv to
		// contextp->commandArgs). An explicit +verilator+seed+0 means "pick a
		// random seed", so dtsim seed 0 is sent as 1.
		seedArg: '+verilator+seed+$([ "$SEED" = 0 ] && echo 1 || echo "$SEED")',

		// The binary also depends on -Mdir and --binary vs C++ harness (the
		// top is in `base`).
		compileKey(c, base) {
			const { mdir, main } = resolved(c.toolOptions);
			return JSON.stringify([base, mdir, main]);
		},

		writeAux(ctx) {
			const wave = ctx.caseOpts.wave;
			if (ctx.phase !== "compile" || !wave.enabled) return;
			writeFileSync(
				join(ctx.dir, "dtsim_wave.sv"),
				waveModule(ctx.caseOpts.top, wave),
			);
		},

		// Runs in the project root: the filelists' relative entries, $VARs
		// and -F are Verilator's own business. -Mdir is under the compile dir.
		compile(ctx) {
			const wave = ctx.caseOpts.wave;
			const { mdir, main, command } = resolved(ctx.caseOpts.toolOptions);
			const top = ctx.caseOpts.top;
			return {
				argv: [
					command,
					...(main ? ["--binary"] : ["--cc", "--exe", "--build"]),
					"--top-module",
					top,
					"-o",
					`V${top}`,
					"-Mdir",
					slash(join(ctx.dir, mdir)),
					...ctx.filelists.flatMap((f) => ["-f", f]),
					...(wave.enabled
						? ["--trace-fst", slash(join(ctx.dir, "dtsim_wave.sv"))]
						: []),
					...ctx.caseOpts.defines.map((d) => `-D${d}`),
					...ctx.caseOpts.compileArgs,
				].map((a) => ctx.expand(a)),
				cwd: ctx.workspace,
				log: join(ctx.dir, "compile.log"),
				logMode: "tee",
				executable: join(
					ctx.dir,
					mdir,
					`V${top}${process.platform === "win32" ? ".exe" : ""}`,
				),
			};
		},

		simulate(ctx) {
			const { mdir } = resolved(ctx.caseOpts.toolOptions);
			return {
				argv: [
					join(ctx.compileDir, mdir, `V${ctx.caseOpts.top}`),
					...ctx.caseOpts.simArgs,
				].map((a) => ctx.expand(a)),
				cwd: ctx.dir,
				log: join(ctx.dir, "sim.log"),
				logMode: "tee",
			};
		},
	};
}
