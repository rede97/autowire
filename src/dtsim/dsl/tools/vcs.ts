// Built-in VCS backend. Everything VCS-shaped (simv, +UVM_*, fsdb, urg,
// verdi) lives here; the core engine never mentions these flags.
// VcsTool({ ntbOpts, flags }); a case's toolOptions may override either.
// ntbOpts picks the -ntb_opts value (default "uvm", e.g. "uvm-1.2"; "" leaves
// -ntb_opts out for a non-UVM bench). flags replaces DEFAULT_FLAGS (older VCS
// releases reject some of them, e.g. O-2018.09 reads "-xlrm nettype_array"
// as a source file). Waveform and coverage come from $DTSIM_WAVE* /
// $DTSIM_COV*, read when the tool is constructed.
import { chmodSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { covFromEnv, waveFromEnv } from "../env.ts";
import type { SimTool, ToolContext, WaveSpec } from "../index.ts";

export type VcsOpts = {
	ntbOpts?: string;
	flags?: readonly string[];
	/** -top (default: VCS finds the top); also the default wave scope and
	 *  run_verdi's -top. */
	top?: string;
	/** The compiler to run (default "vcs"), e.g. a wrapper or a full path. */
	command?: string;
	/** Plusarg that carries the case id (`+<name>=<case>`); false sends none.
	 *  Default "TEST". */
	casePlusarg?: string | false;
};

function topOf(opts: Record<string, unknown>): string | undefined {
	if (opts.top !== undefined && typeof opts.top !== "string") {
		throw new Error("dtsim: vcs top must be a module name");
	}
	return opts.top;
}

const DEFAULT_FLAGS = [
	"-xlrm",
	"nettype_array",
	"+lint=TFIPC-L",
	"-sverilog",
	"-full64",
	"+error+10000",
	"-error=noMPD",
	"-debug_acc+all",
	"-debug_region+cell+encrypt",
	"-timescale=1ns/1ps",
	"-kdb",
	"-lca",
	"+v2k",
	"-v2k_generate",
	"+transport_path_delays",
	"+pulse_e/0",
	"+pulse_r/0",
];

/** Whole ns (at least 1): UVM reads +UVM_TIMEOUT with $sscanf("%d,%s"). */
function parseTimeoutNs(value: string): string {
	const m = /^(\d+(?:\.\d+)?)(s|ms|us|ns|ps)?$/.exec(value.trim());
	if (!m) throw new Error(`dtsim: invalid uvm timeout "${value}"`);
	const scale: Record<string, number> = {
		s: 1e9,
		ms: 1e6,
		us: 1e3,
		ns: 1,
		ps: 0.001,
	};
	const unit = m[2] ?? "ns";
	return String(Math.max(1, Math.ceil(Number(m[1]) * (scale[unit] ?? 1))));
}

function ntbOpts(opts: Record<string, unknown>): string {
	return typeof opts.ntbOpts === "string" ? opts.ntbOpts : "uvm";
}

function compileFlags(opts: Record<string, unknown>): readonly string[] {
	const flags = opts.flags;
	if (flags === undefined) return DEFAULT_FLAGS;
	if (!Array.isArray(flags) || flags.some((f) => typeof f !== "string")) {
		throw new Error("dtsim: vcs flags must be a string array");
	}
	return flags;
}

function command(opts: Record<string, unknown>): string {
	const c = opts.command ?? "vcs";
	if (typeof c !== "string" || c.length === 0) {
		throw new Error("dtsim: vcs command must be a non-empty string");
	}
	return c;
}

function casePlusarg(opts: Record<string, unknown>): string | false {
	const p = opts.casePlusarg ?? "TEST";
	if (p === false) return false;
	if (typeof p !== "string" || !/^[A-Za-z_][A-Za-z0-9_]*$/.test(p)) {
		throw new Error(
			"dtsim: vcs casePlusarg must be a plusarg name (e.g. TEST) or false",
		);
	}
	return p;
}

/** fsdb dump through -ucli (written only with --wave). Scope: $DTSIM_WAVE_TOP,
 *  else `top`, else the whole design. */
function dumpTcl(wave: WaveSpec, top: string | undefined): string {
	const scope = wave.top ?? top;
	return `fsdbDumpfile verilog.fsdb
fsdbDumpvars ${wave.depth}${scope ? ` ${scope}` : ""} "+all"
fsdbDumpSVA
fsdbDumpon
run
`;
}

function verdiScript(ctx: ToolContext, top: string | undefined): string {
	const filelists = ctx.filelists.map((f) => `-f ${f}`).join(" ");
	return `#!/bin/bash
# run_verdi -- generated by dtsim (VCS backend). Filelists are relative to
# the project root, so verdi starts there. -t adds -top <top>.
TOP=""
while [[ $# -gt 0 ]]; do
  case "$1" in
    -t) TOP="${top ? `-top ${top}` : ""}"; shift ;;
    *) shift ;;
  esac
done
cd ${ctx.workspace} || exit 1
verdi -sv ${filelists} -ssf ${join(ctx.dir, "verilog.fsdb")} ${ctx.caseOpts.defines
		.map((d) => `+define+${d}`)
		.join(" ")} $TOP &
`;
}

export function VcsTool(opts: VcsOpts = {}): SimTool {
	// Validate now: a bad option fails at config load, not at first compile.
	ntbOpts(opts);
	compileFlags(opts);
	command(opts);
	casePlusarg(opts);
	topOf(opts);
	const wave = waveFromEnv();
	const cov = covFromEnv();
	const merged = (caseOpts: Record<string, unknown>) => ({
		...opts,
		...caseOpts,
	});
	return {
		kind: "dtsim-tool",
		name: "vcs",
		interactive: true,
		passthrough: [
			"PATH",
			"HOME",
			"USER",
			"LOGNAME",
			"LANG",
			"LC_ALL",
			"TMPDIR",
			"TMP",
			"TEMP",
			"LD_LIBRARY_PATH",
			"VCS_HOME",
			"VERDI_HOME",
			"VC_STATIC_HOME",
			"SYNOPSYS",
			"UVM_HOME",
			"DESIGNWARE_HOME",
			"LM_LICENSE_FILE",
			"SNPSLMD_LICENSE_FILE",
		],
		compileErrors: [/Error-\[/, /^Error:/, /^\*E,/],
		simErrors: [/UVM_ERROR/, /UVM_FATAL/, /Error-\[/, /^Error:/],

		// simv depends on the -ntb_opts library, the flag set and -top too.
		compileKey(c, base) {
			const o = merged(c.toolOptions);
			return JSON.stringify([base, ntbOpts(o), compileFlags(o), topOf(o)]);
		},

		writeAux(ctx) {
			const top = topOf(merged(ctx.caseOpts.toolOptions));
			if (ctx.phase === "compile") {
				if (wave.enabled) {
					writeFileSync(join(ctx.dir, "dump.tcl"), dumpTcl(wave, top));
				}
				if (cov.enabled) {
					const viewer = join(ctx.dir, "verdi_cov");
					writeFileSync(
						viewer,
						`#!/bin/bash\nif [ -d merge.vdb ]; then db=merge.vdb; else db=simv.vdb; fi\nverdi -cov -covdir "$db" &\n`,
					);
					chmodSync(viewer, 0o755);
				}
			} else {
				const script = join(ctx.dir, "run_verdi");
				writeFileSync(script, verdiScript(ctx, top));
				chmodSync(script, 0o755);
			}
		},

		// Runs in the project root: the filelists' relative entries, $VARs
		// and -F are VCS's own business. Every output goes to the compile dir.
		compile(ctx) {
			const o = merged(ctx.caseOpts.toolOptions);
			const top = topOf(o);
			const argv = [
				command(o),
				...compileFlags(o),
				...(ntbOpts(o) ? ["-ntb_opts", ntbOpts(o)] : []),
				...(top ? ["-top", top] : []),
				...ctx.filelists.flatMap((f) => ["-f", f]),
				`-Mdir=${join(ctx.dir, "csrc")}`,
				"-o",
				join(ctx.dir, "simv"),
				"-l",
				join(ctx.dir, "vcs.log"),
				...ctx.caseOpts.defines.map((d) => `+define+${d}`),
				...ctx.caseOpts.compileArgs,
				...(cov.enabled
					? ["-cm", cov.metrics, "-cm_dir", join(ctx.dir, "simv.vdb")]
					: []),
			].map((a) => ctx.expand(a));
			return {
				argv,
				cwd: ctx.workspace,
				log: join(ctx.dir, "vcs.log"),
				logMode: "tool",
				executable: join(ctx.dir, "simv"),
			};
		},

		simulate(ctx) {
			const o = merged(ctx.caseOpts.toolOptions);
			const uvm = ctx.caseOpts.uvm;
			const plusarg = casePlusarg(o);
			const simv = ctx.regression ? join(ctx.compileDir, "simv") : "../simv";
			// UCLI only when it has a job: the fsdb dump, or --interactive.
			const ucli = wave.enabled
				? ["-ucli", "-i", join(ctx.compileDir, "dump.tcl")]
				: ctx.interactive
					? ["-ucli"]
					: [];
			const argv = [
				simv,
				...ucli,
				"-l",
				join(ctx.dir, "sim.log"),
				...(plusarg ? [`+${plusarg}=${ctx.caseId}`] : []),
				"+vcs+lic+wait",
			];
			if (uvm) {
				argv.push(
					`+UVM_TESTNAME=${uvm.test ?? "top_test"}`,
					`+UVM_VERBOSITY=${uvm.verbosity ?? "UVM_HIGH"}`,
					`+UVM_MAX_QUIT_COUNT=${uvm.maxQuit ?? 9999}`,
					// argv, not a shell line: quotes would reach UVM, whose "%d"
					// then reads 0 and every test dies of PH_TIMEOUT at time 0.
					`+UVM_TIMEOUT=${parseTimeoutNs(uvm.timeout ?? "1000ps")},YES`,
					`+test_drain_time=${uvm.drainTime ?? 100}`,
				);
				if (uvm.seq) argv.push(`+user_seq_type=${uvm.seq}`);
			}
			argv.push(...ctx.caseOpts.simArgs);
			if (cov.enabled && ctx.seed !== undefined) {
				const cmName = `${ctx.caseId}_${ctx.seed}`.replace(
					/[^A-Za-z0-9_]/g,
					"_",
				);
				argv.push(
					"-cm",
					cov.metrics,
					"-cm_dir",
					join(ctx.compileDir, "simv.vdb"),
					"-cm_name",
					cmName,
					"-cm_log",
					join(ctx.dir, "cm.log"),
				);
			}
			return {
				argv: argv.map((a) => ctx.expand(a)),
				cwd: ctx.dir,
				log: join(ctx.dir, "sim.log"),
				logMode: "tool",
			};
		},
	};
}
